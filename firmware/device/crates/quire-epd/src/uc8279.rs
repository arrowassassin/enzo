#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn banks_are_command_prefixed_in_register_order() {
        for bank in [&BW_GC, &BW_DU, &XTF_PRE_BW_MID] {
            for (i, t) in bank.iter().enumerate() {
                assert_eq!(t[0], 0x20 + i as u8);
            }
        }
    }

    #[test]
    fn window_covers_792_by_528() {
        let x1 = u16::from_be_bytes([FULL_WINDOW[2], FULL_WINDOW[3]]);
        let y1 = u16::from_be_bytes([FULL_WINDOW[6], FULL_WINDOW[7]]);
        assert_eq!((x1, y1), (791, 527));
    }
}
