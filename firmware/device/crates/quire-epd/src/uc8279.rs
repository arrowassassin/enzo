//! UC8279d_B (X3 units since July 2026) register script and waveform banks.
//!
//! The waveform tables, the init script and the refresh sequences were recovered from the
//! stock Xteink X3 firmware (`update.bin`, July 2026, descriptor set `ZHX368_8279`) by the
//! FreeInk SDK (`libs/display/FreeInkDisplay/src/lut/Uc8279X3Luts.h`, commit `df4a1b7`) and
//! reached us through PapyriX `lib/EInkDisplay/src/Uc8279X3Luts.h` /
//! `docs/x3-uc8279-driver-reference.md`.
//!
//! Copyright (c) 2026 FreeInk — MIT License, see `LICENSE-freeink` in this crate. The tables
//! below are a verbatim copy of `kUc8279X3_*`; only the padding to full length is ours.
//!
//! These modules ship with a **blank MTP**: no `0xA5` refresh-enable key, no factory Command
//! Default Setting, no temperature LUTs. The host must send every register and every waveform
//! (PSR `REG=1`), or the panel stays dark.

use crate::uc8253::Step;

/// Power-on register script (stock function `FUN_42014ad4`, x3-uc8279-driver-reference.md
/// "Power-On Register Script"). Sent after the hardware reset.
pub const INIT_SCRIPT: &[Step] = &[
    // 0x00 PSR: 0x3F 0x4A — REG=1 (external LUT), KW mode; byte 2 as recovered.
    Step { cmd: 0x00, data: &[0x3F, 0x4A] },
    // 0x91 PTIN — enter the partial window; all RAM writes happen inside it (reference "Data
    // Planes": a DTM1 write outside the window misaligns the planes because the controller's
    // native stride is 800 × 600).
    Step { cmd: 0x91, data: &[] },
    // 0x90 PTL — window X 0..791 (0x0000..0x0317), Y 0..527 (0x0000..0x020F), PT_SCAN=1.
    Step { cmd: 0x90, data: &FULL_WINDOW },
    // 0x03 PFS: 0x20.
    Step { cmd: 0x03, data: &[0x20] },
    // 0x01 PWR: 0x43 (VS_EN|VG_EN), 0x00, VSH=0x78, VSL=0x78, VDHR=0x17.
    Step { cmd: 0x01, data: &[0x43, 0x00, 0x78, 0x78, 0x17] },
    // 0x82 VDCS: VCOM DC = 0x24.
    Step { cmd: 0x82, data: &[0x24] },
    // 0x06 BTST: booster 0x25 0x25 0x3C.
    Step { cmd: 0x06, data: &[0x25, 0x25, 0x3C] },
    // 0x30 PLL: 0x0F (frame rate).
    Step { cmd: 0x30, data: &[0x0F] },
    // 0xE1: 0x02 (gate scan).
    Step { cmd: 0xE1, data: &[0x02] },
];

/// PTL (0x90) payload for the full 792 × 528 window (`FULL_WINDOW` in `Uc8279X3Driver.cpp`).
pub const FULL_WINDOW: [u8; 9] = [0x00, 0x00, 0x03, 0x17, 0x00, 0x00, 0x02, 0x0F, 0x01];

/// CDI (0x50) on the first refresh after init (stock `FUN_42013c7e`).
pub const CDI_FIRST: u8 = 0x97;
/// CDI (0x50) on every later refresh (`0x97 | 0x40`).
pub const CDI_LATER: u8 = 0xD7;

/// Number of B/W refreshes after init that must use the GC bank (`initialFullsRemaining_ = 2`).
pub const INITIAL_GC_REFRESHES: u8 = 2;

/// One command-prefixed 43-byte table: byte 0 is the register (0x20..0x24), then 42 data bytes.
pub type BankTable = [u8; 43];
/// A B/W bank: VCOM, WW, BW, WB, BB.
pub type Bank = [BankTable; 5];
/// A raw 49-byte grey table (register sent separately).
pub type GrayTable = [u8; 49];

const fn pad43(src: &[u8]) -> BankTable {
    let mut out = [0u8; 43];
    let mut i = 0;
    while i < src.len() {
        out[i] = src[i];
        i += 1;
    }
    out
}

const fn pad49(src: &[u8]) -> GrayTable {
    let mut out = [0u8; 49];
    let mut i = 0;
    while i < src.len() {
        out[i] = src[i];
        i += 1;
    }
    out
}

