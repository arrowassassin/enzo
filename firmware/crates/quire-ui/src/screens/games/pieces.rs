/// Silhouette for a piece kind (1 pawn … 6 king).
fn art(kind: u8) -> &'static [&'static str; N] {
    match kind {
        1 => &PAWN,
        2 => &KNIGHT,
        3 => &BISHOP,
        4 => &ROOK,
        5 => &QUEEN,
        _ => &KING,
    }
}

fn set(a: &[&str; N], x: i32, y: i32) -> bool {
    if x < 0 || y < 0 || x >= N as i32 || y >= N as i32 {
        return false;
    }
    a[y as usize].as_bytes()[x as usize] == b'#'
}

/// Draw a piece centred in `sq`: `kind` 1–6, `black` for the black side.
pub fn draw_piece(f: &mut Frame, sq: Rect, kind: u8, black: bool) {
    let a = art(kind);
    let scale = 2;
    let size = N as i32 * scale;
    let ox = sq.x + (sq.w as i32 - size) / 2;
    let oy = sq.y + (sq.h as i32 - size) / 2;
    let px = |f: &mut Frame, x: i32, y: i32, ink: Ink| {
        f.fill_rect(Rect::new(ox + x * scale, oy + y * scale, scale as u32, scale as u32), ink);
    };
    for y in 0..N as i32 {
        for x in 0..N as i32 {
            let on = set(a, x, y);
            let near = on || (-1..=1).any(|dy| (-1..=1).any(|dx| set(a, x + dx, y + dy)));
            if black {
                // White halo around a black body.
                if near {
                    px(f, x, y, if on { Ink::Black } else { Ink::White });
                }
            } else if on {
                // Outline pixels: body pixels with a non-body 4-neighbour.
                let edge = !(set(a, x - 1, y) && set(a, x + 1, y) && set(a, x, y - 1) && set(a, x, y + 1));
                px(f, x, y, if edge { Ink::Black } else { Ink::White });
            } else if near {
                px(f, x, y, Ink::White);
            }
        }
    }
}
